"""Detailed investigation of Capability extraction in C4 (and other conditions)."""
import json
from pathlib import Path
from research_pipeline.extractors.raw_artifact import EvaluationCandidate
from research_pipeline.evaluation.matching import match_entities_bipartite, normalize_entity_name, are_semantically_equivalent

gt_path = Path("c:/Users/ksato/workspace/finance/research_pipeline/tests/fixtures/gold_standard/h1a_ground_truth.json")
with open(gt_path, "r", encoding="utf-8") as f:
    ground_truth = json.load(f)

dev_docs = {d["source_id"]: d for d in ground_truth if d.get("split") == "development"}

exp_dir = Path("c:/Users/ksato/workspace/finance/research_pipeline/data/experiments/dev_c0_c4")

print("="*80)
print("CAPABILITY EXTRACTION DETAILED AUDIT FOR C4 (Development Set, 10 Docs, 3 Trials)")
print("="*80)

# Check all C4 bundles
doc_cap_analysis = []

for sid, doc in dev_docs.items():
    gold_caps = [e for e in doc.get("entities", []) if e.get("entity_type") == "capability"]
    gold_methods = [e for e in doc.get("entities", []) if e.get("entity_type") == "method"]
    gold_models = [e for e in doc.get("entities", []) if e.get("entity_type") == "model"]
    
    print(f"\nDocument: {sid} ({doc['target_fields']['title_text'][:50]})")
    print(f"  Gold Capability ({len(gold_caps)}): {[g.get('name') or g.get('statement') for g in gold_caps]}")
    print(f"  Gold Method ({len(gold_methods)}):     {[g.get('name') or g.get('statement') for g in gold_methods]}")
    
    for t in [1, 2, 3]:
        p = exp_dir / f"bundle_dev_C4_t{t}_{sid}.json"
        with open(p, "r", encoding="utf-8") as f:
            b = json.load(f)
        
        raw_parsed = b["raw_artifact"].get("parsed_candidates") or {}
        raw_caps = raw_parsed.get("capabilities", [])
        raw_methods = raw_parsed.get("methods", [])
        
        accepted_caps = [EvaluationCandidate(**c) for c in b.get("evaluation_candidates", []) if c.get("entity_type") == "capability"]
        accepted_methods = [EvaluationCandidate(**c) for c in b.get("evaluation_candidates", []) if c.get("entity_type") == "method"]
        rejections = b.get("rejected_items", [])
        cap_rejections = [r for r in rejections if r.get("entity_type") == "capability"]
        
        # Check matching
        match_res = match_entities_bipartite(gold_caps, accepted_caps, target_entity_type="capability")
        
        print(f"  [Trial {t}]")
        print(f"    Raw capabilities generated by LLM ({len(raw_caps)}): {[c.get('name') for c in raw_caps]}")
        print(f"    Raw methods generated by LLM ({len(raw_methods)}):      {[m.get('name') for m in raw_methods]}")
        print(f"    Capability Rejections ({len(cap_rejections)}): {[r.get('rejection_reason') for r in cap_rejections]}")
        print(f"    Accepted capabilities ({len(accepted_caps)}): {[c.name_or_statement for c in accepted_caps]}")
        print(f"    Capability Match Result: TP={match_res.true_positives}, FP={match_res.false_positives}, FN={match_res.false_negatives}")
        
        # Check if gold capability was generated as a method
        for gc in gold_caps:
            gc_name = gc.get("name") or gc.get("statement") or ""
            gc_syn = gc.get("synonyms", [])
            for am in accepted_methods:
                am_name = am.name_or_statement or ""
                if are_semantically_equivalent(gc_name, gc_syn, am_name):
                    print(f"    >>> CONFUSION DETECTED! Gold Capability '{gc_name}' was extracted as Method '{am_name}'!")
                elif any(word in am_name.lower() for word in gc_name.lower().split() if len(word) > 3):
                    print(f"    >>> PARTIAL OVERLAP: Gold Capability '{gc_name}' vs Extracted Method '{am_name}'")
